def create_sample_size_chart(
    sample_table: pd.DataFrame,
) -> None:
    """Create sample-size sensitivity chart."""
    plt.figure(figsize=(9, 6))

    plt.plot(
        sample_table["relative_mde_pct"],
        sample_table["total_sample_size"],
        marker="o",
    )

    plt.xlabel("Minimum Detectable Relative Lift (%)")

    plt.ylabel("Required Total Sample Size")

    plt.title("A/B Test Sample Size vs Detectable Lift")

    plt.grid(alpha=0.3)

    plt.tight_layout()

    output_path = OUTPUT_DIR / "ab_test_sample_size_sensitivity.png"

    plt.savefig(
        output_path,
        dpi=200,
        bbox_inches="tight",
    )

    plt.close()

    print(f"Saved chart: {output_path}")


