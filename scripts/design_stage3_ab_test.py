import pandas as pd
from scipy.stats import norm  # type: ignore[import-untyped]

PROJECT_ROOT = Path(__file__).resolve().parents[1]

OUTPUT_DIR = PROJECT_ROOT / "reports" / "stage3" / "ab_test"

ALPHA = 0.05
POWER = 0.80

BASELINE_CONVERSION_RATE = 0.01

RELATIVE_MDE_VALUES = [
    0.05,
    0.10,
    0.15,
    0.20,
    0.25,
]

CONTROL_SHARE = 0.50
TREATMENT_SHARE = 0.50

MIN_EXPERIMENT_DAYS = 14


def calculate_sample_size_per_group(
    baseline_rate: float,
    treatment_rate: float,
    alpha: float,
    power: float,
) -> int:
    """Estimate sample size per group for two proportions."""
    if not 0 < baseline_rate < 1:
        raise ValueError("baseline_rate must be between 0 and 1.")

    if not 0 < treatment_rate < 1:
        raise ValueError("treatment_rate must be between 0 and 1.")

    if treatment_rate == baseline_rate:
        raise ValueError("Treatment and baseline rates must differ.")

    z_alpha = norm.ppf(1 - alpha / 2)

    z_power = norm.ppf(power)

    pooled_rate = (baseline_rate + treatment_rate) / 2

    pooled_variance = 2 * pooled_rate * (1 - pooled_rate)

    separate_variance = baseline_rate * (1 - baseline_rate) + treatment_rate * (
        1 - treatment_rate
    )

    numerator = (
        z_alpha * np.sqrt(pooled_variance) + z_power * np.sqrt(separate_variance)
    ) ** 2

    difference = treatment_rate - baseline_rate

    sample_size = numerator / (difference**2)

    return int(np.ceil(sample_size))


def build_sample_size_table() -> pd.DataFrame:
    """Build sample-size scenarios."""
    rows: list[dict[str, Any]] = []

    for relative_mde in RELATIVE_MDE_VALUES:
        treatment_rate = BASELINE_CONVERSION_RATE * (1 + relative_mde)

        absolute_lift = treatment_rate - BASELINE_CONVERSION_RATE

        per_group = calculate_sample_size_per_group(
            BASELINE_CONVERSION_RATE,
            treatment_rate,
            ALPHA,
            POWER,
        )

        total = per_group * 2

        rows.append(
            {
                "baseline_conversion_rate": (BASELINE_CONVERSION_RATE),
                "relative_mde": (relative_mde),
                "relative_mde_pct": (relative_mde * 100),
                "target_treatment_rate": (treatment_rate),
                "absolute_lift": (absolute_lift),
                "sample_size_per_group": (per_group),
                "total_sample_size": (total),
                "alpha": ALPHA,
                "power": POWER,
            }
        )

    result = pd.DataFrame(rows)

    return cast(
        pd.DataFrame,
        result,
    )


